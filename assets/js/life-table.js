/** 표에 실린 가장 높은 연령 */
export const MAX_TABLE_AGE = 100;

/**
 * 성별·연령별 기대여명(년)을 돌려줍니다.
 * @param {number} age    상속개시일 현재 만 나이
 * @param {'male'|'female'|'all'} gender
 * @returns {number|null} 나이가 올바르지 않으면 null
 */
export function getLifeExpectancy(age, gender = 'all') {
  const n = Math.floor(Number(age));
  if (!Number.isFinite(n) || n < 0) return null;

  // 표의 마지막 연령을 넘으면 마지막 값을 사용합니다.
  const row = LIFE_TABLE[Math.min(n, MAX_TABLE_AGE)];
  if (!row) return null;

  const column = gender === 'male' ? 2 : gender === 'female' ? 3 : 1;
  return row[column];
}

/**
 * 장애인공제에 적용할 기대여명 연수.
 * 1년 미만의 기간은 1년으로 보므로 올림합니다.
 */
export function getDeductionYears(age, gender = 'all') {
  const years = getLifeExpectancy(age, gender);
  return years === null ? null : Math.ceil(years);
}

